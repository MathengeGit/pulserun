int textWidth(const std::string& text, int scale) {
    if (text.empty()) return 0;
    return (int)text.size() * 6 * scale - scale;  // 5 columns + 1 column gap per glyph
}

void drawText(Framebuffer& fb, int x, int y, const std::string& text, int scale, Color c) {
    int penX = x;
    for (char ch : text) {
        if (const Glyph* g = findGlyph(ch)) {
            for (int row = 0; row < 7; ++row)
                for (int col = 0; col < 5; ++col)
                    if (g->rows[row] & (1 << (4 - col))) fb.fillRect(penX + col * scale, y + row * scale, scale, scale, c);
        }
        penX += 6 * scale;
    }
}

void drawTextShadow(Framebuffer& fb, int x, int y, const std::string& text, int scale, Color c, Color shadow,
                    int offset) {
    drawText(fb, x + offset, y + offset, text, scale, shadow);
    drawText(fb, x, y, text, scale, c);
}

void drawTextCentered(Framebuffer& fb, int cx, int y, const std::string& text, int scale, Color c) {
    drawText(fb, cx - textWidth(text, scale) / 2, y, text, scale, c);
}
